export function getPostCategory(post: { title: string; content?: string }): 'daily' | 'live' {
  const t = (post.title || '').toLowerCase();
  const c = (post.content || '').toLowerCase();
  if (
    t.includes('[daily]') || 
    t.includes('daily') || 
    t.includes('နေ့စဉ်') || 
    t.includes('bulletin') || 
    c.includes('#daily') || 
    c.includes('သတင်းလွှာ') ||
    t.includes('သတင်းလွှာ')
  ) {
    return 'daily';
  }
  return 'live';
}

export function cleanPostTitle(title: string): string {
  return title.replace(/^\[(daily|live|bulletin)\]\s*/i, '');
}
